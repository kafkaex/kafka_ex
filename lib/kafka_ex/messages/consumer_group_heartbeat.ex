defmodule KafkaEx.Messages.ConsumerGroupHeartbeat do
  @moduledoc """
  The result of a ConsumerGroupHeartbeat request (KIP-848, "consumer" group
  protocol, Kafka 4.0+).

  Java equivalent: `org.apache.kafka.common.message.ConsumerGroupHeartbeatResponseData`

    * `member_id` - the member id. From ConsumerGroupHeartbeat v1 (KIP-1082) it
      is generated by the client; v0 brokers may assign one on join.
    * `member_epoch` - the member's epoch after this heartbeat. Send it with the
      next heartbeat. `-1` after a dynamic member left, `-2` after a static
      member left.
    * `heartbeat_interval_ms` - how often the coordinator expects heartbeats.
    * `assignment` - the member's *new* target assignment as a list of
      `KafkaEx.Messages.TopicPartitions`, or `nil` when it did not change since
      the previous heartbeat. An empty list means "no partitions".
    * `throttle_time_ms` - broker quota throttle time.
  """

  alias KafkaEx.Messages.TopicPartitions

  @type t :: %__MODULE__{
          member_id: String.t() | nil,
          member_epoch: integer(),
          heartbeat_interval_ms: non_neg_integer(),
          assignment: [TopicPartitions.t()] | nil,
          throttle_time_ms: non_neg_integer() | nil
        }

  defstruct [:member_id, :member_epoch, :heartbeat_interval_ms, :assignment, :throttle_time_ms]

  @doc """
  Builds a ConsumerGroupHeartbeat struct from keyword data.
  """
  @spec build(Keyword.t()) :: t()
  def build(opts) do
    %__MODULE__{
      member_id: Keyword.get(opts, :member_id),
      member_epoch: Keyword.fetch!(opts, :member_epoch),
      heartbeat_interval_ms: Keyword.fetch!(opts, :heartbeat_interval_ms),
      assignment: Keyword.get(opts, :assignment),
      throttle_time_ms: Keyword.get(opts, :throttle_time_ms)
    }
  end

  @doc """
  Number of partitions in the new assignment, or `nil` when the assignment did
  not change.
  """
  @spec assigned_partition_count(t()) :: non_neg_integer() | nil
  def assigned_partition_count(%__MODULE__{assignment: nil}), do: nil

  def assigned_partition_count(%__MODULE__{assignment: assignment}) do
    Enum.reduce(assignment, 0, fn %TopicPartitions{partitions: partitions}, acc -> acc + length(partitions) end)
  end
end
