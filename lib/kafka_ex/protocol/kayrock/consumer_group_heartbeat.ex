defmodule KafkaEx.Protocol.Kayrock.ConsumerGroupHeartbeat do
  @moduledoc """
  This module handles ConsumerGroupHeartbeat (API key 68, KIP-848) request &
  response parsing. Request is built using Kayrock protocol, response is parsed
  to native KafkaEx structs.

  ConsumerGroupHeartbeat is the single RPC of the "consumer" group protocol
  (`group.protocol=consumer`, Kafka 4.0+): a member joins (`member_epoch: 0`),
  heartbeats with its current epoch and owned partitions, receives its target
  assignment, and leaves (`member_epoch: -1`, or `-2` for a static member) with
  the same request. Topics are identified by topic id.

  ## Supported Versions

  - **V0**: Kafka 3.7+ (KIP-848)
    - Request: `group_id`, `member_id`, `member_epoch`, `instance_id`, `rack_id`,
      `rebalance_timeout_ms`, `subscribed_topic_names`, `server_assignor`,
      `topic_partitions` (owned; by topic id)
    - Response: `throttle_time_ms`, `error_code`, `error_message`, `member_id`,
      `member_epoch`, `heartbeat_interval_ms`, `assignment` (nullable; by topic id)
  - **V1**: Kafka 4.0+
    - Request: +`subscribed_topic_regex` (KIP-848 regex subscription). The
      member id is generated by the client (KIP-1082).
    - Response: Same as V0

  Both versions are flexible (compact encoding, tagged fields).

  All known versions (V0-V1) have explicit `defimpl` implementations.
  An `Any` fallback is retained for forward compatibility with unknown
  future Kayrock versions.
  """

  defprotocol Request do
    @moduledoc """
    This protocol is used to build ConsumerGroupHeartbeat requests.

    ## Options (V0-V1)
    - `group_id` (required): The consumer group ID
    - `member_id`: The member ID; defaults to `""`. On V0 a join sends `""`
      and the coordinator assigns one. On V1+ (KIP-1082) a join
      (`member_epoch: 0`) with no id (absent, `nil` or `""`) gets one from
      `RequestHelpers.generate_member_id/0`; callers should generate it once
      and pass it so a retried join reuses it. Every later heartbeat must send
      the member's id.
    - `member_epoch` (required): `0` to join, the current epoch to heartbeat,
      `-1` to leave, `-2` for a static member leaving temporarily
    - `instance_id`: static membership instance ID
    - `rack_id`: the member's rack ID
    - `rebalance_timeout_ms`: defaults to `-1` ("unchanged")
    - `subscribed_topic_names`: list of topic names
    - `server_assignor`: server-side assignor name (e.g. `"uniform"`)
    - `topic_partitions`: owned partitions, `[%{topic_id: <<_::128>>, partitions: [integer]}]`

    ## V1 Options (adds to V0)
    - `subscribed_topic_regex`: subscription regex (RE2/J syntax)

    Every optional field defaults to `nil` (`-1` for `rebalance_timeout_ms`),
    which KIP-848 defines as "not provided / unchanged since the last
    heartbeat". Send the full set only on join and after a change.

    All known versions (V0-V1) have explicit implementations.
    The `Any` fallback handles unknown future versions.
    """
    @fallback_to_any true

    @spec build_request(t(), Keyword.t()) :: t()
    def build_request(request, opts)
  end

  defprotocol Response do
    @moduledoc """
    This protocol is used to parse ConsumerGroupHeartbeat responses.

    ## Return Values
    - `{:ok, KafkaEx.Messages.ConsumerGroupHeartbeat.t()}` on success. The
      assignment's `topic_name`s are `nil`; `KafkaEx.Client` fills them in from
      cluster metadata (see `ResponseHelpers.put_topic_names/2`).
    - `{:error, Error.t()}` on error; the broker's `error_message` is in the
      error's metadata.

    All known versions (V0-V1) have explicit implementations.
    The `Any` fallback handles unknown future versions.
    """
    @fallback_to_any true

    alias KafkaEx.Client.Error
    alias KafkaEx.Messages.ConsumerGroupHeartbeat

    @spec parse_response(t()) :: {:ok, ConsumerGroupHeartbeat.t()} | {:error, Error.t()}
    def parse_response(response)
  end
end
